  const localizedCat = CATEGORY_I18N[lang]?.[cat] || cat;
  const village = clone.input_params?.village || clone.input?.village || '';
  const district = clone.input_params?.district || clone.input?.district || '';
  const margin = Number(clone.input_params?.margin_capital || clone.input?.margin_capital || 0).toLocaleString('en-IN');

